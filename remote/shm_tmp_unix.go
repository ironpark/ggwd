//go:build unix && !ios && !android

package remote

import "os"

// anonymousTempFile returns a temporary file that has no name left: an open file needs none.
func anonymousTempFile() (*os.File, error) {
	f, err := os.CreateTemp("", "ggwd-remote-*")
	if err != nil {
		return nil, err
	}
	if err := os.Remove(f.Name()); err != nil {
		_ = f.Close()
		return nil, err
	}
	return f, nil
}
